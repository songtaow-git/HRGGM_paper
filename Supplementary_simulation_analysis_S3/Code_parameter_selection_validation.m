% Computes observed-variable marginal precision by removing H and G via a Schur complement.
function marginal_precision = marginal_local_precision(...
    theta, n_local, nuisance_indices)

    theta_LL = theta(1:n_local, 1:n_local);
    theta_LZ = theta(1:n_local, nuisance_indices);
    theta_ZL = theta(nuisance_indices, 1:n_local);
    theta_ZZ = theta(nuisance_indices, nuisance_indices);

    if rcond(theta_ZZ) < 1e-12
        marginal_precision = nan(n_local);
        return;
    end

    marginal_precision = ...
        theta_LL - theta_LZ * (theta_ZZ \ theta_ZL);

    marginal_precision = ...
        0.5 * (marginal_precision + marginal_precision.');
end

% Computes the population Gaussian loss: tr(Sigma_pop K) - logdet(K).
function loss = population_negative_loglikelihood(...
    precision_matrix, population_covariance)

    precision_matrix = ...
        0.5 * (precision_matrix + precision_matrix.');

    [is_spd, logdet_value] = spd_logdet(precision_matrix);

    if ~is_spd
        loss = NaN;
        return;
    end

    loss = trace(population_covariance * precision_matrix) ...
        - logdet_value;

    if ~isfinite(loss)
        loss = NaN;
    end
end

% Tests positive definiteness and computes the log determinant by Cholesky factorization.
function [is_spd, logdet_value] = spd_logdet(A)

    A = 0.5 * (A + A.');

    [R, flag] = chol(A);

    is_spd = flag == 0;

    if is_spd
        logdet_value = 2 * sum(log(diag(R)));
    else
        logdet_value = NaN;
    end
end

% Computes normalized entropy from all absolute entries of the global-induced matrix.
function entropy_value = normalized_lg_entropy(...
    theta, n_local, global_idx, epsilon_value)

    global_matrix = global_induced_matrix(...
        theta, n_local, global_idx);

    weights = abs(global_matrix(:));
    weights = weights(isfinite(weights));

    total_weight = sum(weights);

    if isempty(weights) || total_weight <= epsilon_value
        entropy_value = 0;
        return;
    end

    probabilities = weights / total_weight;
    probabilities = probabilities(probabilities > 0);

    raw_entropy = -sum(probabilities .* log(probabilities));

    denominator = log(numel(weights));

    if denominator <= 0
        entropy_value = 0;
    else
        entropy_value = raw_entropy / denominator;
    end
end

% Computes the observed-space matrix induced by the hidden global variable.
function global_matrix = global_induced_matrix(...
    theta, n_local, global_idx)

    theta_LG = theta(1:n_local, global_idx);
    theta_GL = theta(global_idx, 1:n_local);
    theta_GG = theta(global_idx, global_idx);

    if ~isfinite(theta_GG) || abs(theta_GG) <= eps
        global_matrix = nan(n_local);
        return;
    end

    global_matrix = ...
        theta_LG * (1 / theta_GG) * theta_GL;

    global_matrix = ...
        0.5 * (global_matrix + global_matrix.');
end

% Computes global-effect magnitude relative to observed-variable marginal precision.
function magnitude = relative_global_magnitude(...
    theta, ...
    n_local, ...
    hidden_idx, ...
    global_idx, ...
    epsilon_value)

    marginal_precision = marginal_local_precision(...
        theta, ...
        n_local, ...
        [hidden_idx, global_idx]);

    global_matrix = global_induced_matrix(...
        theta, ...
        n_local, ...
        global_idx);

    numerator = norm(global_matrix, 'fro');
    denominator = norm(marginal_precision, 'fro') + epsilon_value;

    magnitude = numerator / denominator;

    if ~isfinite(magnitude)
        magnitude = NaN;
    end
end

% Standardizes finite entries while preserving non-finite positions.
function z = standardize_finite_vector(x)

    x = x(:);
    z = nan(size(x));

    valid = isfinite(x);

    if ~any(valid)
        return;
    end

    current = x(valid);
    current_mean = mean(current);
    current_sd = std(current, 0);

    if current_sd <= eps
        z(valid) = 0;
    else
        z(valid) = (current - current_mean) / current_sd;
    end
end

% Computes relative Frobenius error over off-diagonal matrix entries.
function error_value = relative_frobenius_offdiag(A, B)

    A = 0.5 * (A + A.');
    B = 0.5 * (B + B.');

    n = size(A, 1);
    mask = ~eye(n);

    numerator = norm(A(mask) - B(mask), 2);
    denominator = norm(B(mask), 2);

    if denominator <= eps
        error_value = NaN;
    else
        error_value = numerator / denominator;
    end
end

% Computes undirected support precision, recall, F1, and predicted edge count.
function [precision_value, recall_value, f1_value, edge_count] = ...
    native_support_metrics(...
    estimated_LL, ...
    truth_LL, ...
    estimated_threshold, ...
    truth_threshold)

    estimated_LL = 0.5 * (estimated_LL + estimated_LL.');
    truth_LL = 0.5 * (truth_LL + truth_LL.');

    n = size(estimated_LL, 1);
    mask = triu(true(n), 1);

    predicted = abs(estimated_LL(mask)) > estimated_threshold;
    truth = abs(truth_LL(mask)) > truth_threshold;

    TP = sum(predicted & truth);
    FP = sum(predicted & ~truth);
    FN = sum(~predicted & truth);

    edge_count = sum(predicted);

    if TP + FP > 0
        precision_value = TP / (TP + FP);
    else
        precision_value = 0;
    end

    if TP + FN > 0
        recall_value = TP / (TP + FN);
    else
        recall_value = 0;
    end

    if precision_value + recall_value > 0
        f1_value = ...
            2 * precision_value * recall_value / ...
            (precision_value + recall_value);
    else
        f1_value = 0;
    end
end

% Computes Spearman correlation using internally calculated average tied ranks.
function rho = spearman_correlation_no_toolbox(x, y)

    x = x(:);
    y = y(:);

    valid = isfinite(x) & isfinite(y);
    x = x(valid);
    y = y(valid);

    if numel(x) < 2
        rho = NaN;
        return;
    end

    rank_x = average_tied_ranks(x);
    rank_y = average_tied_ranks(y);

    if std(rank_x, 0) <= eps || std(rank_y, 0) <= eps
        rho = NaN;
        return;
    end

    C = corrcoef(rank_x, rank_y);
    rho = C(1, 2);
end

% Assigns average ranks to tied values.
function ranks = average_tied_ranks(x)

    x = x(:);

    [sorted_x, order] = sort(x, 'ascend');
    ranks_sorted = zeros(size(sorted_x));

    i = 1;

    while i <= numel(sorted_x)

        j = i;

        while j < numel(sorted_x) && ...
                sorted_x(j + 1) == sorted_x(i)
            j = j + 1;
        end

        ranks_sorted(i:j) = (i + j) / 2;
        i = j + 1;
    end

    ranks = zeros(size(x));
    ranks(order) = ranks_sorted;
end

