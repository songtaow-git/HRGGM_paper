        'Interpreter', 'tex');

    valid_values = all_values(isfinite(all_values));

    if isempty(valid_values)
        ylim(ax, [0, 1]);
    else
        low = min(valid_values);
        high = max(valid_values);
        span = high - low;

        if span <= eps
            span = max(abs(high), 1) * 0.1;
        end

        ylim(ax, [...
            max(0, low - 0.10 * span), ...
            high + 0.15 * span]);
    end

    grid(ax, 'on');
end

% Creates and exports per-dataset alpha score-comparison panels.
function make_alpha_supplement_figure(...
    results, ...
    noise_colors, ...
    png_file, ...
    pdf_file, ...
    width_in, ...
    height_in, ...
    dpi, ...
    font_name, ...
    tick_font_size, ...
    axis_label_font_size, ...
    panel_title_font_size)

    sort_key = [[results.noise_pct].', [results.repeat_id].'];
    [~, order] = sortrows(sort_key, [1, 2]);
    results = results(order);

    noise_levels = sort(unique([results.noise_pct]));

    fig = figure(...
        'Visible', 'off', ...
        'Color', 'w', ...
        'Units', 'inches', ...
        'Position', [1, 1, width_in, height_in], ...
        'Renderer', 'painters');

    layout = tiledlayout(...
        fig, 3, 3, ...
        'TileSpacing', 'compact', ...
        'Padding', 'compact');

    for i = 1:numel(results)

        ax = nexttile(layout, i);
        hold(ax, 'on');

        noise_index = find(...
            noise_levels == results(i).noise_pct, ...
            1, 'first');

        current_color = noise_colors(noise_index, :);

        x = results(i).alpha_values(:);

        cv_score = standardize_finite_vector(...
            results(i).alpha_cv_score(:));

        population_score = standardize_finite_vector(...
            results(i).alpha_population_score(:));

        plot(...
            ax, x, cv_score, '-', ...
            'Color', [0.25, 0.25, 0.25], ...
            'LineWidth', 1.0, ...
            'DisplayName', 'HR-GGM CV score');

        plot(...
            ax, x, population_score, '-', ...
            'Color', current_color, ...
            'LineWidth', 1.2, ...
            'DisplayName', 'Population score');

        scatter(...
            ax, ...
            x(results(i).selected_alpha_index), ...
            cv_score(results(i).selected_alpha_index), ...
            30, ...
            'Marker', 'p', ...
            'MarkerFaceColor', current_color, ...
            'MarkerEdgeColor', 'k', ...
            'LineWidth', 0.6, ...
            'HandleVisibility', 'off');

        set(ax, 'XScale', 'log');

        xlabel(ax, '\alpha', ...
            'Interpreter', 'tex', ...
            'FontSize', axis_label_font_size);

        ylabel(ax, 'Standardized score', ...
            'FontSize', axis_label_font_size);

        title(...
            ax, ...
            sprintf('%d%% noise, repeat %d', ...
            results(i).noise_pct, results(i).repeat_id), ...
            'FontWeight', 'bold', ...
            'FontSize', panel_title_font_size);

        ax.FontName = font_name;
        ax.FontSize = tick_font_size;
        ax.LineWidth = 0.7;
        ax.TickDir = 'out';
        ax.Layer = 'top';
        ax.Box = 'off';
        ax.GridAlpha = 0.18;

        grid(ax, 'on');

        if i == 1
            legend(ax, ...
                'Location', 'best', ...
                'Box', 'off', ...
                'FontSize', tick_font_size);
        end
    end

    exportgraphics(...
        fig, png_file, ...
        'Resolution', dpi, ...
        'BackgroundColor', 'white');

    exportgraphics(...
        fig, pdf_file, ...
        'ContentType', 'vector', ...
        'BackgroundColor', 'white');

    close(fig);
end

% Blends an RGB color toward white by the specified amount.
function color_out = lighten_color(color_in, amount)

    amount = max(0, min(1, amount));
    color_out = color_in + amount * (1 - color_in);
end

