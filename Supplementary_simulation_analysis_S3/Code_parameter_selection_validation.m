%% Helper functions
% Reads a finite numeric parameter vector from a supported text layout.
function x = read_numeric_vector(filename)

    A = readmatrix(filename);
    A = remove_nan_border(A);

    if isempty(A)
        error('Empty numeric file:\n%s', filename);
    end

    if isvector(A)
        x = A(:);
    elseif size(A, 2) == 2
        x = A(:, end);
    elseif size(A, 1) == 2
        x = A(end, :).';
    else
        error('Expected a numeric vector in:\n%s', filename);
    end

    x = x(isfinite(x));
end

% Reads and validates a score vector against a parameter-grid length.
function score = read_score_vector_for_grid(filename, expected_length)

    A = readmatrix(filename);
    A = remove_nan_border(A);

    if isempty(A)
        error('Empty score file:\n%s', filename);
    end

    if isvector(A)
        score = A(:);
    elseif size(A, 1) == expected_length
        score = A(:, end);
    elseif size(A, 2) == expected_length
        score = A(end, :).';
    else
        error([...
            'Cannot map score file of size %d x %d to a grid of ' ...
            'length %d:\n%s'], ...
            size(A, 1), size(A, 2), expected_length, filename);
    end

    score = score(:);

    if numel(score) ~= expected_length
        error('Score length does not match the parameter grid:\n%s', ...
            filename);
    end

    if any(~isfinite(score))
        error('Score curve contains NaN or Inf:\n%s', filename);
    end
end

% Reads, validates, and symmetrizes a square precision matrix.
function theta = read_theta_matrix(filename, expected_size)

    theta = readmatrix(filename);
    theta = remove_nan_border(theta);

    if ~isequal(size(theta), [expected_size, expected_size])
        error([...
            'Theta size is %d x %d; expected %d x %d:\n%s'], ...
            size(theta, 1), ...
            size(theta, 2), ...
            expected_size, ...
            expected_size, ...
            filename);
    end

    if any(~isfinite(theta), 'all')
        error('Theta contains NaN or Inf:\n%s', filename);
    end

    theta = 0.5 * (theta + theta.');
end

% Removes rows and columns that contain only NaN values.
function A = remove_nan_border(A)

    if isempty(A)
        return;
    end

    A = A(~all(isnan(A), 2), :);
    A = A(:, ~all(isnan(A), 1));
end

% Reports relative matrix asymmetry when it exceeds the specified tolerance.
function validate_theta_matrix(theta, symmetry_tolerance, label)

    relative_asymmetry = ...
        norm(theta - theta.', 'fro') / ...
        max(norm(theta, 'fro'), eps);

    if relative_asymmetry > symmetry_tolerance
        warning('%s relative asymmetry is %.3e.', ...
            label, relative_asymmetry);
    end
end

% Selects the numbered score file with the largest parsed identifier.
function [selected_file, largest_id] = ...
    find_latest_numbered_file(folder, regular_expression)

    files = dir(fullfile(folder, '*'));
    files = files(~[files.isdir]);

    ids = nan(numel(files), 1);

    for i = 1:numel(files)

        token = regexp(...
            files(i).name, ...
            regular_expression, ...
            'tokens', ...
            'once');

        if ~isempty(token)
            ids(i) = str2double(token{1});
        end
    end

    valid = isfinite(ids);

    if ~any(valid)
        error([...
            'No numbered score file matching "%s" was found in:\n%s'], ...
            regular_expression, folder);
    end

    files = files(valid);
    ids = ids(valid);

    [largest_id, index] = max(ids);

    selected_file = fullfile(...
        files(index).folder, ...
        files(index).name);
end

% Locates a unique scan folder and parses its fixed parameter and gamma values.
function [folder_path, fixed_value, gamma_value] = ...
    find_unique_scan_folder(result_root, wildcard_pattern, fixed_name)

    folders = dir(fullfile(result_root, wildcard_pattern));
    folders = folders([folders.isdir]);

    if numel(folders) ~= 1
        error([...
            'Expected exactly one scan folder matching:\n%s\n' ...
            'Found %d under:\n%s'], ...
            wildcard_pattern, numel(folders), result_root);
    end

    folder_name = folders(1).name;

    if strcmpi(fixed_name, 'lambda')
        expression = ...
            '^Theta_by_alpha__fixed_lambda_(.+)__gamma_(.+)$';
    elseif strcmpi(fixed_name, 'alpha')
        expression = ...
            '^Theta_by_lambda__fixed_alpha_(.+)__gamma_(.+)$';
    else
        error('Unknown fixed parameter name: %s', fixed_name);
    end

    token = regexp(folder_name, expression, 'tokens', 'once');

    if isempty(token)
        error('Cannot parse scan-folder parameters:\n%s', folder_name);
    end

    fixed_value = decode_parameter_token(token{1});
    gamma_value = decode_parameter_token(token{2});

    folder_path = fullfile(result_root, folder_name);
end

% Converts filename-safe parameter tokens to numeric values.
function value = decode_parameter_token(token)

    token = strtrim(char(token));

    is_negative = startsWith(token, 'm');

    if is_negative
        token = token(2:end);
    end

    token = strrep(token, 'p', '.');

    value = str2double(token);

    if ~isfinite(value)
        error('Cannot decode numeric parameter token: %s', token);
    end

    if is_negative
        value = -value;
    end
end

% Computes a scale-aware tolerance for parameter comparisons.
function tolerance = parameter_match_tolerance(value, base_tolerance)

    tolerance = max(...
        base_tolerance, ...
        base_tolerance * max(1, abs(value)));
end

% Reads an indexed parameter scan and validates file ordering and matrix dimensions.
function scan = read_scan_matrices(...
    folder, ...
    parameter_name, ...
    parameter_list, ...
    expected_theta_size, ...
    parameter_tolerance, ...
    symmetry_tolerance)

    files = dir(fullfile(...
        folder, ...
        sprintf('Theta_%s_*', lower(parameter_name))));

    files = files(~[files.isdir]);

    indices = nan(numel(files), 1);
    values_from_filename = nan(numel(files), 1);

    for i = 1:numel(files)

        [~, stem, ~] = fileparts(files(i).name);

        expression = sprintf(...
            '^Theta_%s_(\\d+)__value_(.+)$', ...
            lower(parameter_name));

        token = regexp(stem, expression, 'tokens', 'once');

        if isempty(token)
            continue;
        end

        indices(i) = str2double(token{1});
        values_from_filename(i) = ...
            decode_parameter_token(token{2});
    end

    valid = isfinite(indices);

    files = files(valid);
    indices = indices(valid);
    values_from_filename = values_from_filename(valid);

    if isempty(files)
        error('No parseable scan matrices were found in:\n%s', folder);
    end

    [indices, order] = sort(indices);

    files = files(order);
    values_from_filename = values_from_filename(order);

    expected_indices = (1:numel(parameter_list)).';

    if numel(indices) ~= numel(expected_indices) || ...
            any(indices(:) ~= expected_indices)

        error('Scan files are incomplete or misindexed in:\n%s', folder);
    end

    scan = struct(...
        'index', cell(numel(files), 1), ...
        'value', cell(numel(files), 1), ...
        'theta', cell(numel(files), 1), ...
        'file', cell(numel(files), 1));

    for i = 1:numel(files)

        expected_value = parameter_list(i);

        if isfinite(values_from_filename(i))

            allowed_difference = parameter_match_tolerance(...
                expected_value, parameter_tolerance);

            if abs(values_from_filename(i) - expected_value) > ...
                    allowed_difference

                warning([...
                    'Filename value %.12g does not match list value ' ...
                    '%.12g at index %d in:\n%s'], ...
                    values_from_filename(i), ...
                    expected_value, ...
                    i, ...
                    folder);
            end
        end

        theta_file = fullfile(files(i).folder, files(i).name);

        theta = read_theta_matrix(...
            theta_file, expected_theta_size);

        validate_theta_matrix(...
            theta, symmetry_tolerance, theta_file);

        scan(i).index = i;
        scan(i).value = expected_value;
        scan(i).theta = theta;
        scan(i).file = theta_file;
    end
end

