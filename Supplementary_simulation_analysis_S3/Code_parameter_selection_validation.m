%% HR-GGM parameter-selection validation
% Evaluates saved parameter scans for observed variables O, a hidden master
% regulator H, and a hidden global variable G. Ground truth is used only
% for post hoc validation. Dataset folders are beside this script.
% Exported headers use current manuscript terminology; the original
% dataset naming pattern is retained for input compatibility.

clear;
clc;
close all;


%% Analysis settings
% Resolve the analysis root directory from the script location.
script_file = mfilename('fullpath');

if isempty(script_file)
    base_dir = pwd;
else
    base_dir = fileparts(script_file);
end

% Define the dataset naming pattern and output directory.
dataset_pattern = 'Data_200L_LL250_LH040_noise_*pct_rep_*';

output_root = fullfile(...
    base_dir, ...
    'Parameter_Selection_Validation_OUTPUT');

reset_output_folder = true;

% Define the observed-variable, hidden-regulator, and hidden-global indices.
n_local    = 200;
hidden_idx = 201;
global_idx = 202;
n_total    = 202;

% Set numerical tolerances used for parameter matching and symmetry checks.
parameter_tolerance = 1e-10;
symmetry_tolerance  = 1e-7;

% Define ground-truth and estimated support thresholds.
gt_edge_threshold        = 1e-12;
estimated_edge_threshold = 1e-6;

% Set constants used in the alpha population-selection score.
alpha_tau     = 0.20;
alpha_epsilon = 1e-12;

% Set figure dimensions, resolution, typography, and noise-level colors.
figure_width_in  = 7.01;
figure_height_in = 2.78;
figure_dpi       = 1200;

font_name             = 'Arial';
tick_font_size         = 6.3;
axis_label_font_size   = 7.0;
panel_title_font_size  = 7.3;
legend_font_size       = 6.1;

noise_colors = [...
    0.0000, 0.4470, 0.7410; ...
    0.8500, 0.3250, 0.0980; ...
    0.4660, 0.6740, 0.1880];

if reset_output_folder && exist(output_root, 'dir')
    rmdir(output_root, 's');
end

if ~exist(output_root, 'dir')
    mkdir(output_root);
end


%% Dataset discovery
% Locate dataset folders and extract noise levels and repeat identifiers.
folder_list = dir(fullfile(base_dir, dataset_pattern));
folder_list = folder_list([folder_list.isdir]);

dataset_info = struct(...
    'name', {}, ...
    'path', {}, ...
    'noise_pct', {}, ...
    'repeat_id', {});

for i = 1:numel(folder_list)

    folder_name = folder_list(i).name;

    token = regexp(...
        folder_name, ...
        '^Data_200L_LL250_LH040_noise_(\d+)pct_rep_(\d+)$', ...
        'tokens', ...
        'once');

    if isempty(token)
        continue;
    end

    dataset_info(end + 1).name = folder_name; %#ok<SAGROW>
    dataset_info(end).path = fullfile(base_dir, folder_name);
    dataset_info(end).noise_pct = str2double(token{1});
    dataset_info(end).repeat_id = str2double(token{2});
end

if isempty(dataset_info)
    error([...
        'No matching dataset folders were found beside this .m file.\n' ...
        'Expected folder names such as:\n' ...
        'Data_200L_LL250_LH040_noise_000pct_rep_01\n\n' ...
        'Current folder:\n%s'], ...
        base_dir);
end

sort_key = [...
    [dataset_info.noise_pct].', ...
    [dataset_info.repeat_id].'];

[~, order] = sortrows(sort_key, [1, 2]);
dataset_info = dataset_info(order);

% Print the analysis configuration.
fprintf('============================================================\n');
fprintf('HR-GGM parameter-selection validation\n');
fprintf('Base directory: %s\n', base_dir);
fprintf('Datasets found: %d\n', numel(dataset_info));
fprintf('Output directory: %s\n', output_root);


fprintf('============================================================\n');


%% Dataset analysis
% Initialize containers for per-dataset results and tabular outputs.
analysis_results = struct([]);
lambda_rows = cell(0, 1);
alpha_rows = cell(0, 1);
summary_rows = cell(0, 1);

for d = 1:numel(dataset_info)

    dataset_name = dataset_info(d).name;
    dataset_dir  = dataset_info(d).path;
    noise_pct    = dataset_info(d).noise_pct;
    repeat_id    = dataset_info(d).repeat_id;

    fprintf('\n------------------------------------------------------------\n');
    fprintf('Dataset %d/%d: %s\n', ...
        d, numel(dataset_info), dataset_name);
    fprintf('------------------------------------------------------------\n');

    % Resolve dataset-specific input and result paths.
    data_dir = fullfile(dataset_dir, 'Data');
    build_result_dir = fullfile(dataset_dir, 'build', 'Result');
    alpha_metric_dir = fullfile(build_result_dir, 'Alpha_metric');
    lambda_ratio_dir = fullfile(build_result_dir, 'lambda_ratio');
    scan_result_dir  = fullfile(dataset_dir, 'Result');

    alpha_list_file  = fullfile(data_dir, 'Alpha_list.txt');
    lambda_list_file = fullfile(data_dir, 'Lambda_list.txt');
    theta_gt_file    = fullfile(data_dir, 'Theta_full.txt');
    theta_final_file = fullfile(build_result_dir, 'Theta_final.txt');

    % Verify that all required files and directories are present.
    required_paths = {...
        data_dir, ...
        build_result_dir, ...
        alpha_metric_dir, ...
        lambda_ratio_dir, ...
        scan_result_dir, ...
        alpha_list_file, ...
        lambda_list_file, ...
        theta_gt_file, ...
        theta_final_file};

    for p = 1:numel(required_paths)
        if ~(isfile(required_paths{p}) || isfolder(required_paths{p}))
            error('Required path does not exist:\n%s', required_paths{p});
        end
    end

    % Read parameter grids and precision matrices.
    alpha_list  = read_numeric_vector(alpha_list_file);
    lambda_list = read_numeric_vector(lambda_list_file);

    theta_gt = read_theta_matrix(theta_gt_file, n_total);
    theta_final = read_theta_matrix(theta_final_file, n_total);

    validate_theta_matrix(...
        theta_gt, symmetry_tolerance, ...
        sprintf('%s GT', dataset_name));

    validate_theta_matrix(...
        theta_final, symmetry_tolerance, ...
        sprintf('%s Theta_final', dataset_name));

    % Identify selected alpha and lambda values from the latest score vectors.
    [final_alpha_score_file, final_alpha_loop] = ...
        find_latest_numbered_file(...
        alpha_metric_dir, '^Score_vec_?(\d+)');

    [final_lambda_score_file, final_lambda_loop] = ...
        find_latest_numbered_file(...
        lambda_ratio_dir, '^Score_norm_?(\d+)');

    final_alpha_score = read_score_vector_for_grid(...
        final_alpha_score_file, numel(alpha_list));

    final_lambda_score = read_score_vector_for_grid(...
        final_lambda_score_file, numel(lambda_list));

    selected_alpha_index = finite_argmin(final_alpha_score);
    selected_lambda_index = finite_argmax(final_lambda_score);

    selected_alpha = alpha_list(selected_alpha_index);
    selected_lambda = lambda_list(selected_lambda_index);

    fprintf('Selected alpha:  %.12g (index %d; loop %d)\n', ...
        selected_alpha, selected_alpha_index, final_alpha_loop);

    fprintf('Selected lambda: %.12g (index %d; loop %d)\n', ...
        selected_lambda, selected_lambda_index, final_lambda_loop);

    % Locate one-dimensional full-data parameter scans and verify fixed values.
    [alpha_scan_dir, fixed_lambda_in_folder, gamma_alpha] = ...
        find_unique_scan_folder(...
        scan_result_dir, ...
        'Theta_by_alpha__fixed_lambda_*__gamma_*', ...
        'lambda');

    [lambda_scan_dir, fixed_alpha_in_folder, gamma_lambda] = ...
        find_unique_scan_folder(...
        scan_result_dir, ...
        'Theta_by_lambda__fixed_alpha_*__gamma_*', ...
        'alpha');

    if abs(gamma_alpha - gamma_lambda) > 1e-12
        error('Alpha and lambda scans use different gamma values in %s.', ...
            dataset_name);
    end

    gamma_value = gamma_alpha;

    if abs(fixed_alpha_in_folder - selected_alpha) > ...
            parameter_match_tolerance(...
            selected_alpha, parameter_tolerance)

        error([...
            'The lambda-scan folder does not use the selected alpha.\n' ...
            'Dataset: %s\nSelected alpha: %.12g\nFolder alpha: %.12g'], ...
            dataset_name, selected_alpha, fixed_alpha_in_folder);
    end

    if abs(fixed_lambda_in_folder - selected_lambda) > ...
            parameter_match_tolerance(...
            selected_lambda, parameter_tolerance)

        error([...
            'The alpha-scan folder does not use the selected lambda.\n' ...
            'Dataset: %s\nSelected lambda: %.12g\nFolder lambda: %.12g'], ...
            dataset_name, selected_lambda, fixed_lambda_in_folder);
    end

    % Read all alpha-scan and lambda-scan precision matrices.
    alpha_scan = read_scan_matrices(...
        alpha_scan_dir, ...
        'alpha', ...
        alpha_list, ...
        n_total, ...
        parameter_tolerance, ...
        symmetry_tolerance);

    lambda_scan = read_scan_matrices(...
        lambda_scan_dir, ...
        'lambda', ...
        lambda_list, ...
        n_total, ...
        parameter_tolerance, ...
        symmetry_tolerance);


    % Construct the noise-matched population covariance from the ground truth.
    theta_gt_LL = theta_gt(1:n_local, 1:n_local);

    gt_marginal_precision = marginal_local_precision(...
        theta_gt, ...
        n_local, ...
        [hidden_idx, global_idx]);

    [is_spd, ~] = spd_logdet(gt_marginal_precision);

    if ~is_spd
        error('GT marginal precision is not SPD in %s.', dataset_name);
    end

    gt_local_covariance = ...
        gt_marginal_precision \ eye(n_local);

    gt_local_covariance = ...
        0.5 * (gt_local_covariance + gt_local_covariance.');

    gt_local_sd = sqrt(diag(gt_local_covariance));

    if any(~isfinite(gt_local_sd)) || any(gt_local_sd <= 0)
        error('Invalid GT observed-variable variances in %s.', dataset_name);
    end

    gt_local_correlation = ...
        gt_local_covariance ./ ...
        (gt_local_sd * gt_local_sd.');

    gt_local_correlation = ...
        0.5 * (gt_local_correlation + gt_local_correlation.');

    gt_local_correlation(1:n_local + 1:end) = 1;

    noise_fraction = noise_pct / 100;

    if noise_fraction < 0 || noise_fraction >= 1
        error('Noise fraction must be in [0,1) in %s.', dataset_name);
    end

    population_local_covariance = ...
        (1 - noise_fraction) * gt_local_correlation ...
        + noise_fraction * eye(n_local);

    population_local_covariance = ...
        0.5 * (population_local_covariance + ...
        population_local_covariance.');

    [is_spd, ~] = spd_logdet(population_local_covariance);

    if ~is_spd
        error('Population covariance is not SPD in %s.', dataset_name);
    end


    % Evaluate each lambda candidate using observed-block error and support recovery.
    n_lambda = numel(lambda_scan);

    lambda_values = zeros(n_lambda, 1);
    lambda_error  = nan(n_lambda, 1);
    lambda_precision = nan(n_lambda, 1);
    lambda_recall = nan(n_lambda, 1);
    lambda_f1 = nan(n_lambda, 1);
    lambda_edge_count = nan(n_lambda, 1);

    for i = 1:n_lambda

        theta_hat = lambda_scan(i).theta;
        theta_hat_LL = theta_hat(1:n_local, 1:n_local);

        lambda_values(i) = lambda_scan(i).value;

        lambda_error(i) = relative_frobenius_offdiag(...
            theta_hat_LL, theta_gt_LL);

        [lambda_precision(i), ...
         lambda_recall(i), ...
         lambda_f1(i), ...
         lambda_edge_count(i)] = ...
            native_support_metrics(...
            theta_hat_LL, ...
            theta_gt_LL, ...
            estimated_edge_threshold, ...
            gt_edge_threshold);
    end

    selected_lambda_scan_index = ...
        nearest_parameter_index(lambda_values, selected_lambda);

    truth_best_lambda_index = finite_argmin(lambda_error);
    truth_best_lambda = lambda_values(truth_best_lambda_index);


    % Evaluate each alpha candidate using population loss and global-signal structure.
    n_alpha = numel(alpha_scan);

    alpha_values = zeros(n_alpha, 1);
    alpha_population_loss = nan(n_alpha, 1);
    alpha_entropy = nan(n_alpha, 1);
    alpha_global_magnitude = nan(n_alpha, 1);

    for i = 1:n_alpha

        theta_hat = alpha_scan(i).theta;
        alpha_values(i) = alpha_scan(i).value;

        estimated_marginal_precision = ...
            marginal_local_precision(...
            theta_hat, ...
            n_local, ...
            [hidden_idx, global_idx]);

        alpha_population_loss(i) = ...
            population_negative_loglikelihood(...
            estimated_marginal_precision, ...
            population_local_covariance);

        alpha_entropy(i) = normalized_lg_entropy(...
            theta_hat, ...
            n_local, ...
            global_idx, ...
            alpha_epsilon);

        alpha_global_magnitude(i) = relative_global_magnitude(...
            theta_hat, ...
            n_local, ...
            hidden_idx, ...
            global_idx, ...
            alpha_epsilon);
    end

    valid_magnitude = ...
        alpha_global_magnitude(isfinite(alpha_global_magnitude));

    if isempty(valid_magnitude)
        error('No finite alpha global-magnitude values in %s.', ...
            dataset_name);
    end

    magnitude_reference = max(valid_magnitude);

    if magnitude_reference > alpha_epsilon
        alpha_retention = min(...
            1, ...
            max(...
            0, ...
            alpha_global_magnitude ./ ...
            (alpha_tau * magnitude_reference + alpha_epsilon)));
    else
        alpha_retention = zeros(n_alpha, 1);
    end

    alpha_adjusted_entropy = alpha_entropy .* alpha_retention;

    alpha_population_loss_z = ...
        standardize_finite_vector(alpha_population_loss);

    alpha_adjusted_entropy_z = ...
        standardize_finite_vector(alpha_adjusted_entropy);

    alpha_population_score = ...
        0.5 * alpha_population_loss_z ...
        - 0.5 * alpha_adjusted_entropy_z;

    truth_best_alpha_index = finite_argmin(alpha_population_score);
    truth_best_alpha = alpha_values(truth_best_alpha_index);

    selected_alpha_scan_index = ...
        nearest_parameter_index(alpha_values, selected_alpha);

    alpha_population_score_gap = ...
        alpha_population_score ...
        - alpha_population_score(truth_best_alpha_index);

    cv_population_spearman = ...
        spearman_correlation_no_toolbox(...
        final_alpha_score, ...
        alpha_population_score);


    % Store per-dataset parameter curves, optima, and comparison statistics.
    analysis_results(d).dataset = dataset_name;
    analysis_results(d).noise_pct = noise_pct;
    analysis_results(d).repeat_id = repeat_id;

    analysis_results(d).lambda_values = lambda_values;
    analysis_results(d).lambda_error = lambda_error;
    analysis_results(d).lambda_precision = lambda_precision;
    analysis_results(d).lambda_recall = lambda_recall;
    analysis_results(d).lambda_f1 = lambda_f1;
    analysis_results(d).lambda_edge_count = lambda_edge_count;
    analysis_results(d).selected_lambda = selected_lambda;
    analysis_results(d).selected_lambda_index = ...
        selected_lambda_scan_index;
    analysis_results(d).truth_best_lambda = truth_best_lambda;
    analysis_results(d).truth_best_lambda_index = ...
        truth_best_lambda_index;

    analysis_results(d).alpha_values = alpha_values;
    analysis_results(d).alpha_cv_score = final_alpha_score;
    analysis_results(d).alpha_population_loss = ...
        alpha_population_loss;
    analysis_results(d).alpha_population_score = ...
        alpha_population_score;
    analysis_results(d).alpha_population_score_gap = ...
        alpha_population_score_gap;
    analysis_results(d).selected_alpha = selected_alpha;
    analysis_results(d).selected_alpha_index = ...
        selected_alpha_scan_index;
    analysis_results(d).truth_best_alpha = truth_best_alpha;
    analysis_results(d).truth_best_alpha_index = ...
        truth_best_alpha_index;
    analysis_results(d).cv_population_spearman = ...
        cv_population_spearman;

    % Assemble long-format lambda, alpha, and dataset-summary tables.
    lambda_rows{end + 1, 1} = table(...
        repmat(string(dataset_name), n_lambda, 1), ...
        repmat(noise_pct, n_lambda, 1), ...
        repmat(repeat_id, n_lambda, 1), ...
        lambda_values, ...
        lambda_error, ...
        lambda_precision, ...
        lambda_recall, ...
        lambda_f1, ...
        lambda_edge_count, ...
        (1:n_lambda).' == selected_lambda_scan_index, ...
        (1:n_lambda).' == truth_best_lambda_index, ...
        'VariableNames', {...
            'Dataset', ...
            'NoisePct', ...
            'RepeatID', ...
            'Lambda', ...
            'O_OffDiagonal_RelativeError', ...
            'NativePrecision', ...
            'NativeRecall', ...
            'NativeF1', ...
            'NativeEdgeCount', ...
            'IsSelectedByHRGGM', ...
            'IsTruthBasedOptimum'});

    alpha_rows{end + 1, 1} = table(...
        repmat(string(dataset_name), n_alpha, 1), ...
        repmat(noise_pct, n_alpha, 1), ...
        repmat(repeat_id, n_alpha, 1), ...
        alpha_values, ...
        final_alpha_score(:), ...
        alpha_population_loss, ...
        alpha_population_score, ...
        alpha_population_score_gap, ...
        (1:n_alpha).' == selected_alpha_scan_index, ...
        (1:n_alpha).' == truth_best_alpha_index, ...
        'VariableNames', {...
            'Dataset', ...
            'NoisePct', ...
            'RepeatID', ...
            'Alpha', ...
            'HRGGM_CV_Score', ...
            'PopulationGaussianLoss', ...
            'PopulationSelectionScore', ...
            'PopulationSelectionScoreGap', ...
            'IsSelectedByHRGGM', ...
            'IsTruthBasedOptimum'});

    summary_rows{end + 1, 1} = table(...
        string(dataset_name), ...
        noise_pct, ...
        repeat_id, ...
        gamma_value, ...
        selected_lambda, ...
        truth_best_lambda, ...
        lambda_error(selected_lambda_scan_index), ...
        lambda_error(truth_best_lambda_index), ...
        selected_alpha, ...
        truth_best_alpha, ...
        alpha_population_score_gap(selected_alpha_scan_index), ...
        alpha_population_loss(selected_alpha_scan_index), ...
        alpha_population_loss(truth_best_alpha_index), ...
        cv_population_spearman, ...
        'VariableNames', {...
            'Dataset', ...
            'NoisePct', ...
            'RepeatID', ...
            'Gamma', ...
            'SelectedLambda', ...
            'TruthBasedLambda', ...
