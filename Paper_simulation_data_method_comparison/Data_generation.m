                    LV_competitor_indices;

                Best.LV_competitor_mask = ...
                    LV_competitor_mask;
            end
        end
    end

    %% ====================== Candidate validation ========================

    if isempty(fieldnames(Best))
        error('No candidate was evaluated.');
    end
    if require_essential_gate_before_writing && ...
            ~Best.EssentialWriteGatePassed

        error([ ...
            'No candidate passed the essential GT-only write gate. ', ...
            'No observed dataset was written.']);
    end

    %% ================== Selected network structure ======================

    Model = Best.Model;
    prior_indices = Best.prior_indices;

    Idx_h_list = prior_indices - 1;
    Idx_g_list = setdiff((1:n_local)', prior_indices) - 1;

    %% ======================= Sample generation ==========================

    rng(base_seed + rep * 100000 + 90000, 'twister');

    [L_sigma, chol_flag] = chol(Model.Sigma, 'lower');

    if chol_flag ~= 0
        error('Selected covariance matrix is not SPD.');
    end

    Z_clean = randn(n_samples, p) * L_sigma';

    Z_signal = zscore_columns(Z_clean);
    Z_noise = zscore_columns(randn(size(Z_signal)));

    Z_observed = ...
        sqrt(1 - noise_variance_fraction) * Z_signal + ...
        sqrt(noise_variance_fraction) * Z_noise;

    Z_observed = zscore_columns(Z_observed);

    X_local = Z_observed(:, idx_local)';

    %% ========================== Output files ============================

    Theta_full = Model.Theta;

    writematrix( ...
        Theta_full, ...
        fullfile(OutputFolder, 'Theta_full.txt'), ...
        'Delimiter', 'tab');

    writematrix( ...
        Idx_h_list, ...
        fullfile(OutputFolder, 'Idx_h_list.txt'), ...
        'Delimiter', 'tab');

    writematrix( ...
        Idx_g_list, ...
        fullfile(OutputFolder, 'Idx_g_list.txt'), ...
        'Delimiter', 'tab');

    copyfile( ...
        Alpha_list_file, ...
        fullfile(OutputFolder, 'Alpha_list.txt'));

    copyfile( ...
        Lambda_list_file, ...
        fullfile(OutputFolder, 'Lambda_list.txt'));

    write_binary_matrix( ...
        fullfile(OutputFolder, 'Data_whole.bin'), ...
        X_local);
end

