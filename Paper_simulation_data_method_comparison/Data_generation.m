    weights = signs .* magnitudes;
end

function output = orthogonalize_vector(input, reference)

    input = input(:);
    reference = reference(:);

    denominator = reference' * reference;

    if denominator <= eps
        output = input;
        return;
    end

    output = ...
        input - ...
        reference * ...
        ((reference' * input) / denominator);
end

function Model = build_standardized_model( ...
    Theta_LL, ...
    Theta_LH, ...
    Theta_LG, ...
    Theta_HH, ...
    global_diag, ...
    spd_margin, ...
    numerical_zero_threshold)

    n_local = size(Theta_LL, 1);
    n_hidden = size(Theta_LH, 2);
    n_global = size(Theta_LG, 2);

    p = n_local + n_hidden + n_global;

    idx_local = 1:n_local;
    idx_hidden = n_local + (1:n_hidden);
    idx_global = n_local + n_hidden + (1:n_global);

    Theta_unshifted = zeros(p, p);

    Theta_unshifted(idx_local, idx_local) = Theta_LL;

    Theta_unshifted(idx_local, idx_hidden) = Theta_LH;
    Theta_unshifted(idx_hidden, idx_local) = Theta_LH';

    Theta_unshifted(idx_local, idx_global) = Theta_LG;
    Theta_unshifted(idx_global, idx_local) = Theta_LG';

    Theta_unshifted(idx_hidden, idx_hidden) = Theta_HH;
    Theta_unshifted(idx_global, idx_global) = global_diag;

    Theta_unshifted = ...
        (Theta_unshifted + Theta_unshifted') / 2;

    [~, unshifted_flag] = chol(Theta_unshifted);

    if unshifted_flag == 0

        diagonal_shift = 0;
        Theta_generated = Theta_unshifted;

    else

        try
            minimum_eigenvalue = eigs( ...
                Theta_unshifted, ...
                1, ...
                'smallestreal');
        catch
            minimum_eigenvalue = min(eig(Theta_unshifted));
        end

        diagonal_shift = max( ...
            0, ...
            spd_margin - minimum_eigenvalue);

        Theta_generated = ...
            Theta_unshifted + ...
            diagonal_shift * eye(p);
    end

    Theta_generated = ...
        (Theta_generated + Theta_generated') / 2;

    [~, generated_flag] = chol(Theta_generated);

    if generated_flag ~= 0

        minimum_eigenvalue = min(eig(Theta_generated));

        additional_shift = max( ...
            0, ...
            spd_margin - minimum_eigenvalue);

        Theta_generated = ...
            Theta_generated + ...
            additional_shift * eye(p);

        diagonal_shift = diagonal_shift + additional_shift;
    end

    [~, final_generated_flag] = chol(Theta_generated);

    if final_generated_flag ~= 0
        error('Generated precision matrix is not SPD.');
    end

    Sigma_raw = Theta_generated \ eye(p);
    Sigma_raw = (Sigma_raw + Sigma_raw') / 2;

    sd_vector = sqrt(diag(Sigma_raw));

    if any(~isfinite(sd_vector)) || any(sd_vector <= 0)
        error('Invalid covariance diagonal.');
    end

    Sigma = ...
        Sigma_raw ./ ...
        (sd_vector * sd_vector');

    Sigma = (Sigma + Sigma') / 2;

    Theta = Sigma \ eye(p);
    Theta = (Theta + Theta') / 2;

    Theta(abs(Theta) < numerical_zero_threshold) = 0;

    [~, final_flag] = chol(Theta);

    if final_flag ~= 0
        error('Final standardized precision matrix is not SPD.');
    end

    Model = struct();

    Model.Theta_generated = Theta_generated;
    Model.Sigma_raw = Sigma_raw;
    Model.Sigma = Sigma;
    Model.Theta = Theta;
    Model.diagonal_shift = diagonal_shift;
end

function D = structural_and_LV_diagnostics( ...
    H1_loading, ...
    nuisance_hidden_loadings, ...
    global_loading, ...
    hidden_diagonal, ...
    global_diagonal, ...
    prior_indices, ...
    heldout_H1_indices, ...
    LV_competitor_mask, ...
    n_LV_perturbations, ...
    LV_latent_mixing_sd, ...
    LV_feature_noise_sd)

    H1_loading = H1_loading(:);
    global_loading = global_loading(:);

    if isscalar(hidden_diagonal)
        hidden_diagonal = ...
            hidden_diagonal * ones(5, 1);
    else
        hidden_diagonal = hidden_diagonal(:);
    end

    if numel(hidden_diagonal) ~= 5
        error('hidden_diagonal must contain five values.');
    end

    H1_factor = ...
        H1_loading / ...
        sqrt(max(abs(hidden_diagonal(1)), eps));

    H1_trace = sum(H1_factor .^ 2);

    H2H5_factors = zeros(numel(H1_loading), 4);
    H2H5_trace = zeros(4, 1);

    for h = 1:4

        H2H5_factors(:, h) = ...
            nuisance_hidden_loadings(:, h) / ...
            sqrt(max(abs(hidden_diagonal(h + 1)), eps));

        H2H5_trace(h) = ...
            sum(H2H5_factors(:, h) .^ 2);
    end

    global_factor = ...
        global_loading / ...
        sqrt(max(abs(global_diagonal), eps));

    global_trace = sum(global_factor .^ 2);

    nuisance_factor = [ ...
        H2H5_factors, ...
        global_factor];

    [U_N, S_N, ~] = svd(nuisance_factor, 'econ');

    singular_N = diag(S_N);
    nuisance_eigenvalues = singular_N .^ 2;

    total_nuisance_trace = ...
        sum(nuisance_eigenvalues);

    nuisance_rank1_fraction = ...
        nuisance_eigenvalues(1) / ...
        max(total_nuisance_trace, eps);

    nuisance_leading_factor = ...
        sqrt(nuisance_eigenvalues(1)) * ...
        U_N(:, 1);

    total_nuisance_to_H1 = ...
        total_nuisance_trace / ...
        max(H1_trace, eps);

    H2H5_to_H1 = ...
        sum(H2H5_trace) / ...
        max(H1_trace, eps);

    max_single_H2H5_to_H1 = ...
        max(H2H5_trace) / ...
        max(H1_trace, eps);

    global_fraction_of_nuisance = ...
        global_trace / ...
        max(total_nuisance_trace, eps);

    H1_global_absCorr = safe_abs_corr( ...
        H1_factor, ...
        global_factor);

    total_latent_factor = [ ...
        H1_factor, ...
        H2H5_factors, ...
        global_factor];

    LV = exact_quick_proxy_from_factor( ...
        total_latent_factor, ...
        prior_indices, ...
        heldout_H1_indices, ...
        LV_competitor_mask, ...
        H1_factor);

    perturbed_topK = NaN;
    perturbed_2K = NaN;
    perturbed_p90 = NaN;
    perturbed_max = NaN;

    if n_LV_perturbations > 0

        q = size(total_latent_factor, 2);
        n_local = size(total_latent_factor, 1);

        base_rms = ...
            norm(total_latent_factor, 'fro') / ...
            sqrt(max(n_local * q, 1));

        all_topK = nan(n_LV_perturbations, 1);
        all_2K = nan(n_LV_perturbations, 1);

        for b = 1:n_LV_perturbations

            mixing = ...
                eye(q) + ...
                LV_latent_mixing_sd * ...
                randn(q, q) / sqrt(q);

            feature_noise = ...
                LV_feature_noise_sd * ...
                base_rms * ...
                randn(n_local, q);

            current_factor = ...
                total_latent_factor * mixing + ...
                feature_noise;

            Current = exact_quick_proxy_from_factor( ...
                current_factor, ...
                prior_indices, ...
                heldout_H1_indices, ...
                LV_competitor_mask, ...
                H1_factor);

            all_topK(b) = Current.topK_H1_recovery;
            all_2K(b) = Current.twoK_H1_recovery;
        end

        perturbed_topK = median(all_topK, 'omitnan');
        perturbed_2K = median(all_2K, 'omitnan');
        perturbed_p90 = percentile_linear(all_topK, 90);
        perturbed_max = max(all_topK, [], 'omitnan');
    end

    D = struct();

    D.H1_factor = H1_factor;
    D.global_factor = global_factor;
    D.nuisance_leading_factor = nuisance_leading_factor;
    D.total_latent_factor = total_latent_factor;

    D.H1_trace = H1_trace;
    D.H2H5_trace = H2H5_trace;
    D.global_trace = global_trace;

    D.total_nuisance_to_H1_trace_ratio = ...
        total_nuisance_to_H1;

    D.global_fraction_of_nuisance = ...
        global_fraction_of_nuisance;

    D.H2H5_to_H1_trace_ratio = ...
        H2H5_to_H1;

    D.max_single_H2H5_to_H1_trace_ratio = ...
        max_single_H2H5_to_H1;

    D.nuisance_rank1_fraction = ...
        nuisance_rank1_fraction;

    D.H1_global_absCorr = H1_global_absCorr;

    D.LV_exactQuick_selected_rank = LV.selected_rank;
    D.LV_exactQuick_absCorr_H1 = LV.selected_abs_corr_H1;

    D.LV_exactQuick_TopK_H1_recovery = ...
        LV.topK_H1_recovery;

    D.LV_exactQuick_2K_H1_recovery = ...
        LV.twoK_H1_recovery;

    D.LV_exactQuick_TopK_competitor_fraction = ...
        LV.topK_competitor_fraction;

    D.LV_exactQuick_prior_enrichment = ...
        LV.selected_prior_enrichment;

    D.LV_exactQuick_prior_enrichment_margin = ...
        LV.prior_enrichment_margin;

    D.LV_perturbed_Median_TopK_H1_recovery = ...
        perturbed_topK;

    D.LV_perturbed_Median_2K_H1_recovery = ...
        perturbed_2K;

    D.LV_perturbed_P90_TopK_H1_recovery = ...
        perturbed_p90;

    D.LV_perturbed_Max_TopK_H1_recovery = ...
        perturbed_max;
end

function J = joint_hidden_global_proxy( ...
    total_latent_factor, ...
    H1_factor, ...
    nuisance_leading_factor, ...
    prior_indices, ...
    heldout_H1_indices, ...
    LV_competitor_mask, ...
    keep_fractions, ...
    max_iterations, ...
    inner_power_iterations, ...
    tolerance)

    L_total = ...
        total_latent_factor * ...
        total_latent_factor';

    L_total = (L_total + L_total') / 2;

    prior_block = ...
        L_total(prior_indices, prior_indices);

    prior_block = (prior_block + prior_block') / 2;

    [V_prior, E_prior] = eig(prior_block);

    prior_values = real(diag(E_prior));

    [~, prior_order] = sort( ...
        prior_values, ...
        'descend');

    prior_vector = real(V_prior(:, prior_order(1)));

    hidden_seed = ...
        L_total(:, prior_indices) * ...
        prior_vector;

    hidden_seed = ...
        hidden_seed / ...
        max(norm(hidden_seed, 2), eps);

    global_seed = ...
        nuisance_leading_factor / ...
        max(norm(nuisance_leading_factor, 2), eps);

    n_settings = numel(keep_fractions);

    hidden_H1_corr = zeros(n_settings, 1);
    hidden_nuisance_corr = zeros(n_settings, 1);
    hidden_global_corr = zeros(n_settings, 1);
    global_nuisance_corr = zeros(n_settings, 1);

    topK_recovery = zeros(n_settings, 1);
    twoK_recovery = zeros(n_settings, 1);
    topK_competitor_fraction = zeros(n_settings, 1);

    hidden_support_count = zeros(n_settings, 1);

    for s = 1:n_settings

        keep_fraction = keep_fractions(s);

        h = rank1_factor_update( ...
            L_total, ...
            hidden_seed, ...
            keep_fraction, ...
            inner_power_iterations);

        g = rank1_factor_update( ...
            L_total - h * h', ...
            global_seed, ...
            1.0, ...
            inner_power_iterations);

        for iteration = 1:max_iterations

            h_previous = h;
            g_previous = g;

            h = rank1_factor_update( ...
                L_total - g * g', ...
                h, ...
                keep_fraction, ...
                inner_power_iterations);

            g = rank1_factor_update( ...
                L_total - h * h', ...
                g, ...
                1.0, ...
                inner_power_iterations);

            change = max( ...
                sign_invariant_distance(h, h_previous), ...
                sign_invariant_distance(g, g_previous));

            if change < tolerance
                break;
            end
        end

        hidden_H1_corr(s) = safe_abs_corr( ...
            h, ...
            H1_factor);

        hidden_nuisance_corr(s) = safe_abs_corr( ...
            h, ...
            nuisance_leading_factor);

        hidden_global_corr(s) = safe_abs_corr(h, g);

        global_nuisance_corr(s) = safe_abs_corr( ...
            g, ...
            nuisance_leading_factor);

        Recovery = evaluate_loading_ranking( ...
            abs(h), ...
            prior_indices, ...
            heldout_H1_indices, ...
            LV_competitor_mask);

        topK_recovery(s) = ...
            Recovery.topK_H1_recovery;

        twoK_recovery(s) = ...
            Recovery.twoK_H1_recovery;

        topK_competitor_fraction(s) = ...
            Recovery.topK_competitor_fraction;

        hidden_support_count(s) = ...
            nnz(abs(h) > 1e-10);
    end

    J = struct();

    J.JointProxy_keep_fractions = ...
        keep_fractions(:);

    J.JointProxy_hidden_H1_absCorr_by_setting = ...
        hidden_H1_corr;

    J.JointProxy_hidden_nuisance_absCorr_by_setting = ...
        hidden_nuisance_corr;

    J.JointProxy_hidden_global_absCorr_by_setting = ...
        hidden_global_corr;

    J.JointProxy_global_nuisance_absCorr_by_setting = ...
        global_nuisance_corr;

    J.JointProxy_TopK_H1_recovery_by_setting = ...
        topK_recovery;

    J.JointProxy_2K_H1_recovery_by_setting = ...
        twoK_recovery;

    J.JointProxy_TopK_competitor_fraction_by_setting = ...
        topK_competitor_fraction;

    J.JointProxy_hidden_support_count_by_setting = ...
        hidden_support_count;

    J.JointProxy_min_hidden_H1_absCorr = ...
        min(hidden_H1_corr);

    J.JointProxy_max_hidden_nuisance_absCorr = ...
        max(hidden_nuisance_corr);

    J.JointProxy_max_hidden_global_absCorr = ...
        max(hidden_global_corr);

    J.JointProxy_min_global_nuisance_absCorr = ...
        min(global_nuisance_corr);

    J.JointProxy_min_TopK_H1_recovery = ...
        min(topK_recovery);

    J.JointProxy_min_2K_H1_recovery = ...
        min(twoK_recovery);

    J.JointProxy_max_TopK_competitor_fraction = ...
        max(topK_competitor_fraction);

    J.JointProxy_max_hidden_support_count = ...
        max(hidden_support_count);
end

function factor = rank1_factor_update( ...
    residual_matrix, ...
    initial_vector, ...
    keep_fraction, ...
    max_iterations)

    residual_matrix = ...
        (residual_matrix + residual_matrix') / 2;

    v = initial_vector(:);

    if norm(v, 2) <= eps
        v = randn(size(residual_matrix, 1), 1);
    end

    v = v / norm(v, 2);

    n = numel(v);

    keep_count = max( ...
        1, ...
        min(n, round(keep_fraction * n)));

    for iteration = 1:max_iterations

        y = residual_matrix * v;

        if keep_fraction < 0.999

            absolute_y = abs(y);

            [~, order] = sort( ...
                absolute_y, ...
                'descend');

            mask = false(n, 1);
            mask(order(1:keep_count)) = true;

            % Apply support selection and shrink retained values.
            selected_values = absolute_y(mask);

            if isempty(selected_values)
                threshold = 0;
            else
                threshold = 0.10 * median(selected_values);
            end

            y(~mask) = 0;

            y(mask) = ...
                sign(y(mask)) .* ...
                max(abs(y(mask)) - threshold, 0);
        end

        if norm(y, 2) <= eps
            break;
        end

        y = y / norm(y, 2);

        if sign_invariant_distance(y, v) < 1e-7
            v = y;
            break;
        end

        v = y;
    end

    rayleigh_value = real(v' * residual_matrix * v);
    rayleigh_value = max(rayleigh_value, 0);

    factor = sqrt(rayleigh_value) * v;
end

function distance = sign_invariant_distance(x, y)

    x = x(:);
    y = y(:);

    if norm(x, 2) <= eps && norm(y, 2) <= eps
        distance = 0;
        return;
    end

    x = x / max(norm(x, 2), eps);
    y = y / max(norm(y, 2), eps);

    distance = min( ...
        norm(x - y, 2), ...
        norm(x + y, 2));
end

function R = exact_quick_proxy_from_factor( ...
    Factor, ...
    prior_indices, ...
    heldout_H1_indices, ...
    LV_competitor_mask, ...
    H1_factor)

    n_local = size(Factor, 1);

    [U, S, ~] = svd(Factor, 'econ');

    singular_values = diag(S);
    eigenvalues = singular_values .^ 2;

    threshold = max( ...
        1e-12, ...
        1e-8 * max(eigenvalues));

    keep = eigenvalues > threshold;

    U = U(:, keep);
    eigenvalues = eigenvalues(keep);

    n_components = numel(eigenvalues);

    if n_components < 1
        error('No positive latent component was retained.');
    end

    prior_enrichment = zeros(n_components, 1);
    component_scores = zeros(n_local, n_components);
    component_corr_H1 = zeros(n_components, 1);

    for k = 1:n_components

        feature_score = ...
            sqrt(eigenvalues(k)) * ...
            abs(U(:, k));

        component_scores(:, k) = feature_score;

        feature_score_z = zscore_vector_safe(feature_score);

        prior_enrichment(k) = ...
            mean(feature_score_z(prior_indices));

        component_corr_H1(k) = safe_abs_corr( ...
            U(:, k), ...
            H1_factor);
    end

    [selected_enrichment, selected_rank] = ...
        max(prior_enrichment);

    sorted_enrichment = sort( ...
        prior_enrichment, ...
        'descend');

    if numel(sorted_enrichment) >= 2
        enrichment_margin = ...
            sorted_enrichment(1) - ...
            sorted_enrichment(2);
    else
        enrichment_margin = Inf;
    end

    selected_score = ...
        component_scores(:, selected_rank);

    Ranking = evaluate_loading_ranking( ...
        selected_score, ...
        prior_indices, ...
        heldout_H1_indices, ...
        LV_competitor_mask);

    R = struct();

    R.selected_rank = selected_rank;

    R.selected_abs_corr_H1 = ...
        component_corr_H1(selected_rank);

    R.topK_H1_recovery = ...
        Ranking.topK_H1_recovery;

    R.twoK_H1_recovery = ...
        Ranking.twoK_H1_recovery;

    R.topK_competitor_fraction = ...
        Ranking.topK_competitor_fraction;

    R.selected_prior_enrichment = ...
        selected_enrichment;

    R.prior_enrichment_margin = ...
        enrichment_margin;
end

function R = evaluate_loading_ranking( ...
    score, ...
    prior_indices, ...
    heldout_H1_indices, ...
    LV_competitor_mask)

    n_local = numel(score);

    candidate_indices = setdiff( ...
        (1:n_local)', ...
        prior_indices(:));

    [~, order] = sort( ...
        abs(score(candidate_indices)), ...
        'descend');

    ranked_candidates = candidate_indices(order);

    K = numel(heldout_H1_indices);

    heldout_mask = false(n_local, 1);
    heldout_mask(heldout_H1_indices) = true;

    topK_count = min(K, numel(ranked_candidates));
    twoK_count = min(2 * K, numel(ranked_candidates));

    topK_indices = ranked_candidates(1:topK_count);

    topK_H1_recovery = ...
        sum(heldout_mask(topK_indices)) / K;

    twoK_H1_recovery = ...
        sum(heldout_mask( ...
            ranked_candidates(1:twoK_count))) / K;

    topK_competitor_fraction = ...
        sum(LV_competitor_mask(topK_indices)) / ...
        max(topK_count, 1);

    R = struct();

    R.topK_H1_recovery = topK_H1_recovery;
    R.twoK_H1_recovery = twoK_H1_recovery;

    R.topK_competitor_fraction = ...
        topK_competitor_fraction;
end

function score = raw_candidate_score( ...
    D, ...
    target_total_nuisance_to_H1, ...
    target_global_fraction, ...
    target_H2H5_to_H1, ...
    target_max_single_H2H5_to_H1, ...
    target_nuisance_rank1_fraction, ...
    target_H1_global_absCorr, ...
    target_LV_topK, ...
    target_LV_2K, ...
    target_LV_competitor_fraction)

    score = ...
        8.0 * abs( ...
            D.total_nuisance_to_H1_trace_ratio - ...
            target_total_nuisance_to_H1) + ...
        8.0 * abs( ...
            D.global_fraction_of_nuisance - ...
            target_global_fraction) + ...
        8.0 * abs( ...
            D.H2H5_to_H1_trace_ratio - ...
            target_H2H5_to_H1) + ...
        10.0 * abs( ...
            D.max_single_H2H5_to_H1_trace_ratio - ...
            target_max_single_H2H5_to_H1) + ...
        8.0 * abs( ...
            D.nuisance_rank1_fraction - ...
            target_nuisance_rank1_fraction) + ...
        7.0 * abs( ...
            D.H1_global_absCorr - ...
            target_H1_global_absCorr) + ...
        18.0 * abs( ...
            D.LV_exactQuick_TopK_H1_recovery - ...
            target_LV_topK) + ...
        8.0 * abs( ...
            D.LV_exactQuick_2K_H1_recovery - ...
            target_LV_2K) + ...
        12.0 * abs( ...
            D.LV_exactQuick_TopK_competitor_fraction - ...
            target_LV_competitor_fraction);

    if D.LV_exactQuick_TopK_H1_recovery > 0.60
        score = score + ...
            180.0 * ...
            (D.LV_exactQuick_TopK_H1_recovery - 0.60);
    end
end

function score = full_candidate_score( ...
    D, ...
    target_total_nuisance_to_H1, ...
    target_global_fraction, ...
    target_H2H5_to_H1, ...
    target_max_single_H2H5_to_H1, ...
    target_nuisance_rank1_fraction, ...
    target_H1_global_absCorr, ...
    target_joint_hidden_H1_corr, ...
    target_joint_hidden_nuisance_corr, ...
    target_joint_hidden_global_corr, ...
    target_joint_global_nuisance_corr, ...
    target_joint_topK, ...
    target_joint_2K, ...
    target_LV_topK, ...
    target_LV_2K, ...
    target_LV_competitor_fraction, ...
    target_LV_perturbed_p90)

    score = raw_candidate_score( ...
        D, ...
        target_total_nuisance_to_H1, ...
        target_global_fraction, ...
        target_H2H5_to_H1, ...
        target_max_single_H2H5_to_H1, ...
        target_nuisance_rank1_fraction, ...
        target_H1_global_absCorr, ...
        target_LV_topK, ...
        target_LV_2K, ...
        target_LV_competitor_fraction);

    score = score + ...
        12.0 * abs( ...
            D.JointProxy_min_hidden_H1_absCorr - ...
            target_joint_hidden_H1_corr) + ...
        12.0 * abs( ...
            D.JointProxy_max_hidden_nuisance_absCorr - ...
            target_joint_hidden_nuisance_corr) + ...
        14.0 * abs( ...
            D.JointProxy_max_hidden_global_absCorr - ...
            target_joint_hidden_global_corr) + ...
        10.0 * abs( ...
            D.JointProxy_min_global_nuisance_absCorr - ...
            target_joint_global_nuisance_corr) + ...
        18.0 * abs( ...
            D.JointProxy_min_TopK_H1_recovery - ...
            target_joint_topK) + ...
        8.0 * abs( ...
            D.JointProxy_min_2K_H1_recovery - ...
            target_joint_2K) + ...
        10.0 * abs( ...
            D.LV_perturbed_P90_TopK_H1_recovery - ...
            target_LV_perturbed_p90);

    if D.JointProxy_max_hidden_global_absCorr > 0.58
        score = score + ...
            200.0 * ...
            (D.JointProxy_max_hidden_global_absCorr - 0.58);
    end

    if D.JointProxy_min_TopK_H1_recovery < 0.72
        score = score + ...
            180.0 * ...
            (0.72 - D.JointProxy_min_TopK_H1_recovery);
    end
end

function output = merge_structs(A, B)

    output = A;

    fields = fieldnames(B);

    for i = 1:numel(fields)
        output.(fields{i}) = B.(fields{i});
    end
end

function value = safe_abs_corr(x, y)

    x = x(:);
    y = y(:);

    if std(x) <= eps || std(y) <= eps
        value = 0;
        return;
    end

    value = abs(corr( ...
        x, ...
        y, ...
        'Type', 'Pearson', ...
        'Rows', 'complete'));
end

function z = zscore_vector_safe(x)

    x = x(:);

    mu = mean(x);
    sigma = std(x, 0);

    if ~isfinite(sigma) || sigma <= eps
        z = zeros(size(x));
    else
        z = (x - mu) / sigma;
    end
end

function value = percentile_linear(x, percentile_value)

    x = x(:);
    x = x(isfinite(x));

    if isempty(x)
        value = NaN;
        return;
    end

    x = sort(x, 'ascend');

    if numel(x) == 1
        value = x;
        return;
    end

    position = ...
        1 + ...
        (percentile_value / 100) * ...
        (numel(x) - 1);

    lower_index = floor(position);
    upper_index = ceil(position);

    if lower_index == upper_index
        value = x(lower_index);
    else
        weight = position - lower_index;

        value = ...
            (1 - weight) * x(lower_index) + ...
            weight * x(upper_index);
    end
end

function tf = in_window(value, window)

    tf = value >= window(1) && value <= window(2);
end

function Z = zscore_columns(X)

    means = mean(X, 1);
    sds = std(X, 0, 1);

    sds(sds == 0) = 1;

    Z = (X - means) ./ sds;
end


function write_binary_matrix(filename, Matrix)

    fid = fopen(filename, 'wb');

    if fid == -1
        error('Cannot open binary file: %s', filename);
    end

    fwrite(fid, uint64(size(Matrix, 1)), 'uint64');
    fwrite(fid, uint64(size(Matrix, 2)), 'uint64');

    % Transpose before writing to preserve the expected row-major layout.
    fwrite(fid, Matrix.', 'double');

    fclose(fid);
end
