function signs = balanced_random_signs(n)

    n_positive = ceil(n / 2);
    n_negative = n - n_positive;

    signs = [ ...
        ones(n_positive, 1); ...
        -ones(n_negative, 1)];

    signs = signs(randperm(n));
end

