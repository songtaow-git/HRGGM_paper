%% ========================================================================
% Simulation data generator for a 500-local, 5-hidden, 1-global network.
%
% Network structure:
%   500 local nodes arranged in 100 groups of five
%   5 hidden nodes and 1 global node
%   200 within-group LL edges and 400 between-group LL edges
%   75 H1-connected local nodes: 30 prior and 45 held-out nodes
%   28 non-H1 local nodes with elevated global loadings
%
% The script constructs candidate precision matrices, validates the selected
% structure, generates standardized observations, and writes the model input
% files and ground-truth precision matrix for each repeat.
%
% Each Data folder contains:
%   Alpha_list.txt, Data_whole.bin, Idx_g_list.txt,
%   Idx_h_list.txt, Lambda_list.txt, and Theta_full.txt.
%% ========================================================================

clear;
clc;
close all force;
echo off;
diary off;
warning_state = warning;
warning_cleanup = onCleanup(@() warning(warning_state)); %#ok<NASGU>
warning('off', 'all');

%% =========================== Output settings =============================

script_file = mfilename('fullpath');

if isempty(script_file)
    input_folder = pwd;
else
    input_folder = fileparts(script_file);
end

Alpha_list_file = fullfile(input_folder, 'Alpha_list.txt');
Lambda_list_file = fullfile(input_folder, 'Lambda_list.txt');

if ~isfile(Alpha_list_file)
    error('Required input file does not exist: %s', Alpha_list_file);
end

if ~isfile(Lambda_list_file)
    error('Required input file does not exist: %s', Lambda_list_file);
end

RootOutputFolder = fullfile( ...
    pwd, ...
    'Sim_500L_5H_globalDominant_25pct');

reset_output_folder = true;
require_essential_gate_before_writing = true;

if reset_output_folder && exist(RootOutputFolder, 'dir')
    rmdir(RootOutputFolder, 's');
end

if ~exist(RootOutputFolder, 'dir')
    mkdir(RootOutputFolder);
end

%% ========================= Network dimensions ============================

n_nodes_per_group = 5;
n_groups = 100;
n_local = n_nodes_per_group * n_groups;  % 500

n_hidden = 5;
n_global = 1;

n_samples = 10000;
n_repeats = 3;

p = n_local + n_hidden + n_global;

idx_local = 1:n_local;
idx_hidden = n_local + (1:n_hidden);      % 501:505
idx_global = n_local + n_hidden + 1;      % 506

%% ========================= Dataset generation ============================

noise_variance_fraction = 0.25;
base_seed = 2026;

n_topology_attempts = 18;
n_parameter_draws_per_topology = 360;
n_full_evaluations_per_topology = 12;

%% ========================= H1 node structure =============================

n_anchor_prior = 20;
n_weak_nuisance_prior = 10;
n_prior = n_anchor_prior + n_weak_nuisance_prior;  % 30

n_H1_strong_heldout = 36;
n_H1_weak_heldout = 9;
n_H1_heldout = ...
    n_H1_strong_heldout + ...
    n_H1_weak_heldout;                              % 45

n_H1_total = n_prior + n_H1_heldout;                % 75

H1_anchor_abs_range = [0.46, 0.56];
H1_regular_prior_abs_range = [0.39, 0.49];

H1_strong_heldout_abs_range = [0.35, 0.44];
H1_weak_heldout_abs_range = [0.23, 0.30];

%% ================= Hidden and global node structure ======================

% Number of non-H1 local nodes with elevated global loadings.
n_LV_competitors = 28;

global_background_abs_range = [0.85, 1.05];

global_competitor_shape_range = [0.90, 1.10];
global_competitor_multiplier_range = [5.0, 22.0];

anchor_global_multiplier = 0.12;
weak_prior_global_multiplier = 0.32;

hidden_global_alignment_range = [0.93, 0.98];

hidden_residual_abs_range = [0.70, 1.00];

%% ======================== LL network structure ===========================

n_within_LL_per_group = 2;
n_within_LL = n_groups * n_within_LL_per_group;  % 200
n_between_LL = 400;

forced_H1_cross_fraction = 0.12;
n_forced_H1_cross = round( ...
    forced_H1_cross_fraction * n_between_LL);

within_LL_abs_range = [0.24, 0.43];
between_LL_abs_range = [0.17, 0.34];

group_id = repelem((1:n_groups)', n_nodes_per_group);

all_pairs = nchoosek(1:n_local, 2);

between_pair_mask = ...
    group_id(all_pairs(:, 1)) ~= ...
    group_id(all_pairs(:, 2));

all_between_pairs = all_pairs(between_pair_mask, :);

%% =================== Precision matrix construction =======================

local_diag = 3.0;
hidden_diag = 4.5;
global_diag = 5.0;

spd_margin = 0.10;
numerical_zero_threshold = 1e-10;

%% ======================== Candidate generation ===========================

rho_H1_global_range = [0.10, 0.30];

total_nuisance_to_H1_range = [0.72, 1.10];

global_fraction_of_nuisance_range = [0.65, 0.80];

regular_prior_scale_range = [0.96, 1.10];
heldout_H1_scale_range = [0.96, 1.12];

%% ===================== Joint factor evaluation ===========================

joint_hidden_keep_fractions = [0.20, 0.40, 0.65, 0.85];

joint_max_iterations = 45;
joint_inner_power_iterations = 35;
joint_convergence_tolerance = 1e-6;

%% ================= Latent-factor perturbation evaluation =================

n_LV_perturbations = 24;
LV_latent_mixing_sd = 0.055;
LV_feature_noise_sd = 0.010;

%% ========================== Candidate scoring ============================

target_total_nuisance_to_H1 = 0.90;
target_global_fraction = 0.72;
target_H2H5_to_H1 = 0.25;
target_max_single_H2H5_to_H1 = 0.07;
target_nuisance_rank1_fraction = 0.94;
target_H1_global_absCorr = 0.09;

target_joint_hidden_H1_corr = 0.84;
target_joint_hidden_nuisance_corr = 0.30;
target_joint_hidden_global_corr = 0.30;
target_joint_global_nuisance_corr = 0.88;
target_joint_topK = 0.86;
target_joint_2K = 0.97;

target_LV_topK = 0.50;
target_LV_2K = 0.74;
target_LV_competitor_fraction = 0.47;
target_LV_perturbed_p90 = 0.62;

%% ======================== Candidate selection ============================

preferred_total_nuisance_to_H1 = [0.78, 1.04];
preferred_global_fraction = [0.65, 0.80];
preferred_H2H5_to_H1 = [0.15, 0.35];
preferred_max_single_H2H5_to_H1_max = 0.10;
preferred_nuisance_rank1_fraction = [0.86, 0.985];
preferred_H1_global_absCorr = [0.10, 0.30];

preferred_joint_hidden_H1_corr_min = 0.76;
preferred_joint_hidden_nuisance_corr_max = 0.46;
preferred_joint_hidden_global_corr_max = 0.50;
preferred_joint_global_nuisance_corr_min = 0.76;
preferred_joint_topK = [0.78, 0.94];
preferred_joint_2K_min = 0.92;
preferred_joint_competitor_fraction_max = 0.22;

preferred_LV_topK = [0.38, 0.58];
preferred_LV_2K = [0.55, 0.90];
preferred_LV_competitor_fraction = [0.35, 0.58];
preferred_LV_perturbed_p90_max = 0.68;

%% ======================== Output validation ==============================

essential_total_nuisance_to_H1 = [0.65, 1.18];
essential_global_fraction = [0.58, 0.86];
essential_H2H5_to_H1_max = 0.42;
essential_max_single_H2H5_to_H1_max = 0.13;
essential_nuisance_rank1_fraction_min = 0.80;
essential_H1_global_absCorr_max = 0.34;

essential_joint_hidden_H1_corr_min = 0.68;
essential_joint_hidden_nuisance_corr_max = 0.55;
essential_joint_hidden_global_corr_max = 0.58;
essential_joint_global_nuisance_corr_min = 0.68;
essential_joint_topK_min = 0.72;
essential_joint_2K_min = 0.86;
essential_joint_competitor_fraction_max = 0.32;

essential_LV_topK_max = 0.60;
essential_LV_competitor_fraction_min = 0.30;
essential_LV_perturbed_p90_max = 0.72;

%% ======================== Model parameter files ==========================

% Existing parameter-list files are copied into each output folder.

%% =========================== Dataset repeats =============================

for rep = 1:n_repeats

    OutputFolder = fullfile( ...
        RootOutputFolder, ...
        sprintf('rep_%02d', rep), ...
        'Data');

    if ~exist(OutputFolder, 'dir')
        mkdir(OutputFolder);
    end

    Best = struct();
    best_selection_score = Inf;

    %% ================= Network candidate generation =====================

    for topology_attempt = 1:n_topology_attempts

        rng( ...
            base_seed + rep * 100000 + topology_attempt, ...
            'twister');

        %% ---------------------- H1 node assignment -----------------------

        prior_groups = sort(randperm(n_groups, n_prior));

        prior_indices = zeros(n_prior, 1);

        for j = 1:n_prior

            current_group = prior_groups(j);

            current_group_indices = ...
                ((current_group - 1) * n_nodes_per_group + 1): ...
                (current_group * n_nodes_per_group);

            prior_indices(j) = ...
                current_group_indices(randi(n_nodes_per_group));
        end

        prior_indices = sort(prior_indices(:));

        prior_order = prior_indices(randperm(n_prior));

        anchor_prior_indices = sort( ...
            prior_order(1:n_anchor_prior));

        weak_nuisance_prior_indices = sort( ...
            prior_order( ...
                n_anchor_prior + ...
                (1:n_weak_nuisance_prior)));

        remaining_after_prior = setdiff( ...
            (1:n_local)', ...
            prior_indices);

        heldout_H1_indices = random_subset( ...
            remaining_after_prior, ...
            n_H1_heldout);

        heldout_order = ...
            heldout_H1_indices(randperm(n_H1_heldout));

        strong_heldout_H1_indices = sort( ...
            heldout_order(1:n_H1_strong_heldout));

        weak_heldout_H1_indices = sort( ...
            heldout_order( ...
                n_H1_strong_heldout + ...
                (1:n_H1_weak_heldout)));

        H1_targets = sort([ ...
            prior_indices; ...
            heldout_H1_indices]);

        H1_target_mask = false(n_local, 1);
        H1_target_mask(H1_targets) = true;

        %% -------------------- H1 loading construction --------------------

        H1_base = zeros(n_local, 1);

        H1_base(anchor_prior_indices) = ...
            balanced_random_signs(n_anchor_prior) .* ...
            random_positive_weights( ...
                n_anchor_prior, ...
                H1_anchor_abs_range);

        H1_base(weak_nuisance_prior_indices) = ...
            balanced_random_signs(n_weak_nuisance_prior) .* ...
            random_positive_weights( ...
                n_weak_nuisance_prior, ...
                H1_regular_prior_abs_range);

        H1_base(strong_heldout_H1_indices) = ...
            random_signed_weights( ...
                n_H1_strong_heldout, ...
                H1_strong_heldout_abs_range);

        H1_base(weak_heldout_H1_indices) = ...
            random_signed_weights( ...
                n_H1_weak_heldout, ...
                H1_weak_heldout_abs_range);

        %% --------------- Global-loading node assignment -----------------

        nonH1_pool = find(~H1_target_mask);

        LV_competitor_indices = random_subset( ...
            nonH1_pool, ...
            n_LV_competitors);

        LV_competitor_mask = false(n_local, 1);
        LV_competitor_mask( ...
            LV_competitor_indices) = true;

        %% ------------------ Global loading construction ------------------

        global_background_base = random_signed_weights( ...
            n_local, ...
            global_background_abs_range);

        global_competitor_shape = ...
            random_positive_weights( ...
                n_LV_competitors, ...
                global_competitor_shape_range);

        H1_unit_base = ...
            H1_base / ...
            max(norm(H1_base, 2), eps);

        %% ------------- Additional hidden loading construction -----------

        hidden_residual_basis = zeros(n_local, 4);

        for h = 1:4

            residual = random_signed_weights( ...
                n_local, ...
                hidden_residual_abs_range);

            residual(anchor_prior_indices) = ...
                anchor_global_multiplier * ...
                residual(anchor_prior_indices);

            residual(weak_nuisance_prior_indices) = ...
                weak_prior_global_multiplier * ...
                residual(weak_nuisance_prior_indices);

            residual = orthogonalize_vector( ...
                residual, ...
                H1_unit_base);

            for previous = 1:(h - 1)
                residual = orthogonalize_vector( ...
                    residual, ...
                    hidden_residual_basis(:, previous));
            end

            if norm(residual, 2) <= 1e-10
                error('Hidden residual basis construction failed.');
            end

            hidden_residual_basis(:, h) = ...
                residual / norm(residual, 2);
        end

        %% -------------------- LL precision block -------------------------

        Theta_LL = local_diag * eye(n_local);

        within_edge_list = zeros(n_within_LL, 2);
        within_counter = 0;

        for g = 1:n_groups

            current_group_indices = ...
                ((g - 1) * n_nodes_per_group + 1): ...
                (g * n_nodes_per_group);

            group_pairs = nchoosek(current_group_indices, 2);

            selected = randperm( ...
                size(group_pairs, 1), ...
                n_within_LL_per_group);

            for e = 1:n_within_LL_per_group

                i = group_pairs(selected(e), 1);
                j = group_pairs(selected(e), 2);

                w = random_signed_weight(within_LL_abs_range);

                Theta_LL(i, j) = w;
                Theta_LL(j, i) = w;

                within_counter = within_counter + 1;
                within_edge_list(within_counter, :) = [i, j];
            end
        end

        nonH1_features = find(~H1_target_mask);

        forced_candidates = [];

        for i = 1:numel(H1_targets)

            current_H1 = H1_targets(i);

            valid_nonH1 = nonH1_features( ...
                group_id(nonH1_features) ~= ...
                group_id(current_H1));

            forced_candidates = [ ...
                forced_candidates; ...
                [repmat(current_H1, numel(valid_nonH1), 1), ...
                 valid_nonH1(:)]]; %#ok<AGROW>
        end

        forced_candidates = unique( ...
            sort(forced_candidates, 2), ...
            'rows');

        forced_ids = randperm( ...
            size(forced_candidates, 1), ...
            n_forced_H1_cross);

        forced_pairs = forced_candidates(forced_ids, :);

        remaining_between_candidates = setdiff( ...
            all_between_pairs, ...
            forced_pairs, ...
            'rows');

        remaining_between_count = ...
            n_between_LL - n_forced_H1_cross;

        remaining_ids = randperm( ...
            size(remaining_between_candidates, 1), ...
            remaining_between_count);

        selected_between_pairs = [ ...
            forced_pairs; ...
            remaining_between_candidates(remaining_ids, :)];

        for e = 1:size(selected_between_pairs, 1)

            i = selected_between_pairs(e, 1);
            j = selected_between_pairs(e, 2);

            w = random_signed_weight(between_LL_abs_range);

            Theta_LL(i, j) = w;
            Theta_LL(j, i) = w;
        end

        %% ---------------- Candidate loading generation ------------------

        RawCandidates = repmat( ...
            empty_raw_candidate(), ...
            n_parameter_draws_per_topology, ...
            1);

        for draw = 1:n_parameter_draws_per_topology

            rho_H1_global = random_uniform( ...
                rho_H1_global_range);

            total_nuisance_to_H1_target = ...
                random_uniform( ...
                    total_nuisance_to_H1_range);

            global_fraction_target = ...
                random_uniform( ...
                    global_fraction_of_nuisance_range);

            regular_prior_scale = ...
                random_uniform( ...
                    regular_prior_scale_range);

            heldout_H1_scale = ...
                random_uniform( ...
                    heldout_H1_scale_range);

            hidden_alignments = ...
                hidden_global_alignment_range(1) + ...
                diff(hidden_global_alignment_range) * ...
                rand(4, 1);

            competitor_multiplier = random_uniform( ...
                global_competitor_multiplier_range);

            H1_loading = H1_base;

            H1_loading(weak_nuisance_prior_indices) = ...
                regular_prior_scale * ...
                H1_base(weak_nuisance_prior_indices);

            H1_loading(heldout_H1_indices) = ...
                heldout_H1_scale * ...
                H1_base(heldout_H1_indices);

            H1_unit = ...
                H1_loading / ...
                max(norm(H1_loading, 2), eps);

            global_base = global_background_base;

            global_base(LV_competitor_indices) = ...
                sign_nonzero( ...
                    global_background_base( ...
                        LV_competitor_indices)) .* ...
                competitor_multiplier .* ...
                global_competitor_shape;

            global_base(anchor_prior_indices) = ...
                anchor_global_multiplier * ...
                global_base(anchor_prior_indices);

            global_base(weak_nuisance_prior_indices) = ...
                weak_prior_global_multiplier * ...
                global_base(weak_nuisance_prior_indices);

            global_orthogonal = orthogonalize_vector( ...
                global_base, ...
                H1_unit);

            global_orthogonal = ...
                global_orthogonal / ...
                max(norm(global_orthogonal, 2), eps);

            global_direction = ...
                rho_H1_global * H1_unit + ...
                sqrt(max(1 - rho_H1_global ^ 2, 0)) * ...
                global_orthogonal;

            tiny_floor = 1e-4;

            global_direction( ...
                abs(global_direction) < tiny_floor) = ...
                tiny_floor * sign_nonzero( ...
                    global_direction( ...
                        abs(global_direction) < tiny_floor));

            global_direction = ...
                global_direction / ...
                max(norm(global_direction, 2), eps);

            nuisance_directions = zeros(n_local, 4);

            for h = 1:4

                residual = hidden_residual_basis(:, h);

                residual = orthogonalize_vector( ...
                    residual, ...
                    global_direction);

                residual = ...
                    residual / ...
                    max(norm(residual, 2), eps);

                nuisance_directions(:, h) = ...
                    hidden_alignments(h) * ...
                    global_direction + ...
                    sqrt(max( ...
                        1 - hidden_alignments(h) ^ 2, ...
                        0)) * residual;

                nuisance_directions(:, h) = ...
                    nuisance_directions(:, h) / ...
                    max(norm(nuisance_directions(:, h), 2), eps);
            end

            H1_trace_raw = ...
                sum(H1_loading .^ 2) / hidden_diag;

            total_nuisance_trace_target = ...
                total_nuisance_to_H1_target * ...
                H1_trace_raw;

            global_trace_target = ...
                global_fraction_target * ...
                total_nuisance_trace_target;

            H2H5_trace_target = ...
                total_nuisance_trace_target - ...
                global_trace_target;

            hidden_shares = 0.88 + 0.24 * rand(4, 1);
            hidden_shares = hidden_shares / sum(hidden_shares);

            nuisance_hidden_loadings = zeros(n_local, 4);

            for h = 1:4

                current_trace_target = ...
                    H2H5_trace_target * ...
                    hidden_shares(h);

                current_norm_target = sqrt( ...
                    current_trace_target * hidden_diag);

                nuisance_hidden_loadings(:, h) = ...
                    current_norm_target * ...
                    nuisance_directions(:, h);
            end

            global_norm_target = sqrt( ...
                global_trace_target * global_diag);

            global_loading = ...
                global_norm_target * ...
                global_direction;

            RawD = structural_and_LV_diagnostics( ...
                H1_loading, ...
                nuisance_hidden_loadings, ...
                global_loading, ...
                hidden_diag, ...
                global_diag, ...
                prior_indices, ...
                heldout_H1_indices, ...
                LV_competitor_mask, ...
                0, ...
                0, ...
                0);

            raw_score = raw_candidate_score( ...
                RawD, ...
                target_total_nuisance_to_H1, ...
                target_global_fraction, ...
                target_H2H5_to_H1, ...
                target_max_single_H2H5_to_H1, ...
                target_nuisance_rank1_fraction, ...
                target_H1_global_absCorr, ...
                target_LV_topK, ...
                target_LV_2K, ...
                target_LV_competitor_fraction);

            RawCandidates(draw).rho_H1_global = ...
                rho_H1_global;

            RawCandidates(draw).total_nuisance_to_H1_target = ...
                total_nuisance_to_H1_target;

            RawCandidates(draw).global_fraction_target = ...
                global_fraction_target;

            RawCandidates(draw).regular_prior_scale = ...
                regular_prior_scale;

            RawCandidates(draw).heldout_H1_scale = ...
                heldout_H1_scale;

            RawCandidates(draw).hidden_alignments = ...
                hidden_alignments;

            RawCandidates(draw).competitor_multiplier = ...
                competitor_multiplier;

            RawCandidates(draw).H1_loading = ...
                H1_loading;

            RawCandidates(draw).nuisance_hidden_loadings = ...
                nuisance_hidden_loadings;

            RawCandidates(draw).global_loading = ...
                global_loading;

            RawCandidates(draw).RawDiagnostics = RawD;
            RawCandidates(draw).score = raw_score;
        end

        raw_scores = [RawCandidates.score]';
        [~, raw_order] = sort(raw_scores, 'ascend');

        full_order = raw_order( ...
            1:min(n_full_evaluations_per_topology, ...
                  numel(raw_order)));

        %% ---------------- Candidate matrix evaluation -------------------

        for shortlist_index = 1:numel(full_order)

            Raw = RawCandidates(full_order(shortlist_index));

            Theta_LH = [ ...
                Raw.H1_loading, ...
                Raw.nuisance_hidden_loadings];

            Theta_LG = Raw.global_loading;
            Theta_HH = hidden_diag * eye(n_hidden);

            Model = build_standardized_model( ...
                Theta_LL, ...
                Theta_LH, ...
                Theta_LG, ...
                Theta_HH, ...
                global_diag, ...
                spd_margin, ...
                numerical_zero_threshold);

            H1_loading_final = ...
                Model.Theta(idx_local, idx_hidden(1));

            nuisance_hidden_final = ...
                Model.Theta(idx_local, idx_hidden(2:5));

            global_loading_final = ...
                Model.Theta(idx_local, idx_global);

            hidden_diagonal_final = diag( ...
                Model.Theta(idx_hidden, idx_hidden));

            global_diagonal_final = ...
                Model.Theta(idx_global, idx_global);

            FullD = structural_and_LV_diagnostics( ...
                H1_loading_final, ...
                nuisance_hidden_final, ...
                global_loading_final, ...
                hidden_diagonal_final, ...
                global_diagonal_final, ...
                prior_indices, ...
                heldout_H1_indices, ...
                LV_competitor_mask, ...
                n_LV_perturbations, ...
                LV_latent_mixing_sd, ...
                LV_feature_noise_sd);

            JointD = joint_hidden_global_proxy( ...
                FullD.total_latent_factor, ...
                FullD.H1_factor, ...
                FullD.nuisance_leading_factor, ...
                prior_indices, ...
                heldout_H1_indices, ...
                LV_competitor_mask, ...
                joint_hidden_keep_fractions, ...
                joint_max_iterations, ...
                joint_inner_power_iterations, ...
                joint_convergence_tolerance);

            FullD = merge_structs(FullD, JointD);

            full_score = full_candidate_score( ...
                FullD, ...
                target_total_nuisance_to_H1, ...
                target_global_fraction, ...
                target_H2H5_to_H1, ...
                target_max_single_H2H5_to_H1, ...
                target_nuisance_rank1_fraction, ...
                target_H1_global_absCorr, ...
                target_joint_hidden_H1_corr, ...
                target_joint_hidden_nuisance_corr, ...
                target_joint_hidden_global_corr, ...
                target_joint_global_nuisance_corr, ...
                target_joint_topK, ...
                target_joint_2K, ...
                target_LV_topK, ...
                target_LV_2K, ...
                target_LV_competitor_fraction, ...
                target_LV_perturbed_p90);

            PreferredGatePassed = ...
                in_window( ...
                    FullD.total_nuisance_to_H1_trace_ratio, ...
                    preferred_total_nuisance_to_H1) && ...
                in_window( ...
                    FullD.global_fraction_of_nuisance, ...
                    preferred_global_fraction) && ...
                in_window( ...
                    FullD.H2H5_to_H1_trace_ratio, ...
                    preferred_H2H5_to_H1) && ...
                FullD.max_single_H2H5_to_H1_trace_ratio <= ...
                    preferred_max_single_H2H5_to_H1_max && ...
                in_window( ...
                    FullD.nuisance_rank1_fraction, ...
