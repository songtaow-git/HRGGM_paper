                    essential_H1_global_absCorr_max && ...
                FullD.JointProxy_min_hidden_H1_absCorr >= ...
                    essential_joint_hidden_H1_corr_min && ...
                FullD.JointProxy_max_hidden_nuisance_absCorr <= ...
                    essential_joint_hidden_nuisance_corr_max && ...
                FullD.JointProxy_max_hidden_global_absCorr <= ...
                    essential_joint_hidden_global_corr_max && ...
                FullD.JointProxy_min_global_nuisance_absCorr >= ...
